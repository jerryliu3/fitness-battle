import { createElement, type ReactNode } from "react";
import { act, create, type ReactTestRenderer } from "react-test-renderer";
import { afterEach, expect, it, vi } from "vitest";
import { defaultFieldAppearance, freshState, weeklyRaceCourse } from "@fitness-battle/shared";
import type { FieldModel } from "../model";
vi.mock("next/navigation", () => ({ usePathname: () => "/app/arena" }));
vi.mock("@/components/auth-context", () => ({ useAuth: () => ({ user: null }) }));
vi.mock("@/components/compete-context", () => ({ useCompete: () => ({ debugActive: true }) }));
vi.mock("@/features/course/use-competition-course", () => ({ useCompetitionCourse: (_sport: string, start: string) => ({ course: weeklyRaceCourse(new Date(start)), error: "", retry() {} }) }));
vi.mock("@/lib/haptics", () => ({ playCue() {} }));
vi.mock("./field-course", () => ({ useFieldAppearance: () => [defaultFieldAppearance], FieldOverview: "FieldOverview" }));
vi.mock("@/features/course/geographic-course", () => ({ GeographicCourse: "GeographicCourse" }));
vi.mock("@/features/club/portrait-field", () => ({ PortraitField: "PortraitField" }));
vi.mock("@/features/focus/arena-lanes", () => ({ ArenaLanes: "ArenaLanes" }));
vi.mock("@/features/brand/polished-racer", () => ({ PolishedRacer: "PolishedRacer" }));
vi.mock("@/ui/user-avatar", () => ({ UserAvatar: "UserAvatar" }));
vi.mock("@/features/replay/competition-replay", () => ({ CompetitionReplayButton: "ReplayButton" }));
vi.mock("./expanding-field", () => ({ ExpandingField: ({ children, hud, open }: { children: ReactNode; hud: ReactNode; open: boolean }) => createElement("FieldHost", { open }, children, hud) }));
import { FieldStage } from "./field-stage";
let renderer: ReactTestRenderer;
afterEach(async () => { if (renderer) await act(async () => renderer.unmount()); vi.unstubAllGlobals(); });
it("shares fullscreen, athlete panels, selection and course replay with 4D", async () => {
  vi.stubGlobal("IS_REACT_ACT_ENVIRONMENT", true);
  const you = { id: "you", name: "You", initials: "Y", km: [0, 0, 1] as [number, number, number], place: 2, effort: 1, you: true };
  const peer = { ...you, id: "peer", name: "Peer", initials: "P", km: [0, 0, 2] as [number, number, number], place: 1, you: false };
  const model: FieldModel = { sport: "running", track: "open", periodStart: "2026-10-26T04:00:00Z", periodEnd: "2026-11-02T05:00:00Z", runners: [you, peer], ghost: null, you, referenceKm: 2, checkpointLabels: ["Mon", "Wed", "Now"], gps: true, unit: "km" };
  await act(async () => { renderer = create(createElement(FieldStage, { model, replayState: freshState(new Date("2026-10-26T18:00:00Z")) })); });
  const button = (label: string) => renderer.root.findAllByType("button").find(node => node.props["aria-label"] === label)!;
  const choose = async (value: string) => act(async () => renderer.root.findByType("select").props.onChange({ target: { value } }));
  await choose("4d");
  const map = () => renderer.root.findByType("GeographicCourse" as never);
  const course = weeklyRaceCourse(new Date(model.periodStart));
  expect(map().props.course).toBe(course);
  expect(map().props.onCourseChange).toBeUndefined();
  expect(renderer.root.findAllByType("FieldOverview" as never)).toHaveLength(0);
  await act(async () => button("Expand 4D course to full screen").props.onClick());
  expect(renderer.root.findByType("FieldHost" as never).props.open).toBe(true);
  const overview = () => renderer.root.findByType("FieldOverview" as never);
  expect(overview().props.positionOnly).toBe(true);
  await act(async () => overview().props.onNavigate(.75));
  expect(map().props.distanceTarget).toMatchObject({ value: .75, request: 1 });
  expect(overview().props.view.center).toBe(.75);
  expect(map().props.selectedId).toBe("you");
  await act(async () => map().props.onResumeFollow());
  expect(map().props.distanceTarget).toBeNull();
  await act(async () => button("Collapse athlete panel").props.onClick());
  await act(async () => overview().props.onNavigate(.5));
  expect(map().props.distanceTarget.value).toBe(.5);
  await act(async () => button("Collapse live intervals").props.onClick());
  expect(button("Expand live intervals").props["aria-expanded"]).toBe(false);
  await act(async () => map().props.onSelect("peer"));
  expect(map().props.selectedId).toBe("peer");
  expect(map().props.distanceTarget).toBeNull();
  expect(overview().props.view.center).toBe(2);
  expect(renderer.root.findByType("ReplayButton" as never).props).toMatchObject({ dimension: "4d" });
  expect(renderer.root.findByType("ReplayButton" as never).props.course).toBeUndefined();
  await choose("3d");
  expect(renderer.root.findAllByType("FieldOverview" as never)).toHaveLength(1);
  expect(renderer.root.findByType("FieldHost" as never).props.open).toBe(true);
  await choose("4d");
  expect(overview().props.positionOnly).toBe(true);
  expect(map().props.course).toBe(course);
  expect(map().props.selectedId).toBe("peer");
  expect(button("Expand live intervals")).toBeDefined();
});
