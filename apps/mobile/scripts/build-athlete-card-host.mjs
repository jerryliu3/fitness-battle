// Regenerate on macOS after editing the shared crest or updating its assets.
import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const mobile = fileURLToPath(new URL("../", import.meta.url));
const web = join(mobile, "../web");
const scratch = mkdtempSync(join(tmpdir(), "athlete-card-"));
const publicFiles = join(web, "public");
const ranks = join(publicFiles, "rank-symbols");
const dataUrl = (path, mime) => `data:${mime};base64,${readFileSync(path).toString("base64")}`;

try {
  const assets = {};
  for (const [name, input] of [
    ["brand", join(publicFiles, "brand/overtaek/mark-transparent.png")],
    ...readdirSync(ranks).filter(file => file.endsWith(".png")).map(file => [file.slice(0, -4), join(ranks, file)]),
  ]) {
    const output = join(scratch, `${name}.png`);
    execFileSync("sips", ["-Z", name === "brand" ? "192" : "256", input, "--out", output]);
    assets[name] = dataUrl(output, "image/png");
  }

  const result = await build({
    absWorkingDir: mobile,
    entryPoints: [join(web, "src/features/athlete-card/bundled-scene.tsx")],
    outdir: scratch,
    bundle: true,
    write: false,
    minify: true,
    legalComments: "inline",
    jsx: "automatic",
    define: { assets: JSON.stringify(assets) },
  });
  const javascript = result.outputFiles.find(file => file.path.endsWith(".js")).text;
  const css = result.outputFiles.find(file => file.path.endsWith(".css")).text;
  const fonts = join(web, "src/app/fonts");
  const display = dataUrl(join(fonts, "bebasneue/BebasNeue-Regular.woff2"), "font/woff2");
  const body = dataUrl(join(fonts, "manrope/Manrope[wght].woff2"), "font/woff2");
  const form = dataUrl(join(fonts, "spacegrotesk/SpaceGrotesk[wght].woff2"), "font/woff2");
  const html = `<!doctype html><html lang="en"><meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<style>
@font-face{font-family:Bebas;src:url(${display})}
@font-face{font-family:Manrope;src:url(${body});font-weight:200 800}
@font-face{font-family:SpaceGrotesk;src:url(${form});font-weight:300 700}
:root{--font-display:Bebas;--font-body:Manrope;--font-form:SpaceGrotesk}
*{box-sizing:border-box}
body{margin:0;padding:0 2.5%;overflow:hidden}
h2,h3,p,dl,dd{margin:0}
${css}
</style><div id="root"></div><script>${javascript.replaceAll("</script", "<\\/script")}</script></html>`;
  writeFileSync(join(mobile, "assets/athlete-card-host/scene.cjs"), `// Generated by build:athlete-card-host.\nmodule.exports = ${JSON.stringify(html)};\n`);
} finally {
  rmSync(scratch, { recursive: true, force: true });
}
