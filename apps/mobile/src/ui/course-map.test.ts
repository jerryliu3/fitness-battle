it("delegates native camera frames, pauses following on gestures, and flies from the observed position", async () => {
  vi.stubGlobal("IS_REACT_ACT_ENVIRONMENT", true);
  const course = createRaceCourse("City", [[0, 0], [.02, 0]]);
  const props = { course, optionsTop: 110, onReplay: vi.fn(), lanes: [{ id: "you", name: "You", initials: "Y", you: true, value: .5 }, { id: "peer", name: "Peer", initials: "P", value: 1 }], unit: "km", selectedId: "you", focusRequest: 0, onSelect: vi.fn() };
  await act(async () => { renderer = create(createElement(CourseMap, props), { createNodeMock: element => element.type === "Camera" ? calls : null }); });
  await act(async () => renderer.root.findByType("Map" as never).props.onDidFinishLoadingMap());
  expect(renderer.root.findAllByType("ShapeSource" as never).some(node => node.props.id === "course")).toBe(false);
  calls.setCamera.mockClear();
  await act(async () => renderer.root.findByType("Observer" as never).props.onCameraChanged({ nativeEvent: { properties: { center: [.005, 0], zoom: 15, pitch: 30, heading: 20, isUserInteraction: true } } }));
  expect(calls.setCamera).not.toHaveBeenCalled();
  calls.setCamera.mockClear();
  const updated = { ...props, lanes: props.lanes.map(lane => ({ ...lane, value: lane.value + .1 })) };
  await act(async () => renderer.update(createElement(CourseMap, updated)));
  expect(calls.setCamera).not.toHaveBeenCalled();
  const trails = renderer.root.findAllByType("ShapeSource" as never).find(node => node.props.id === "completed")!.props.shape;
  await act(async () => renderer.update(createElement(CourseMap, { ...updated, selectedId: "peer", focusRequest: 1 })));
  const flight = calls.setCamera.mock.lastCall![0];
  expect(flight.animationDuration).toBeGreaterThan(500);
  const marker = renderer.root.findAllByType("ShapeSource" as never).find(node => node.props.id === "athletes")!.props.shape.features.find((f: any) => f.id === "peer");
  expect(flight.centerCoordinate).toEqual(marker.geometry.coordinates);
  expect(flight.zoomLevel).toBe(15);
  expect(flight.centerCoordinate[0]).toBeGreaterThan(.005);
  expect(renderer.root.findAllByType("Map" as never)).toHaveLength(1);
  expect(renderer.root.findAllByType("ShapeSource" as never).find(node => node.props.id === "completed")!.props.shape).toBe(trails);
  expect(renderer.root.findByType("Camera" as never).props.maxZoomLevel).toBe(20);
  const button = (label: string) => renderer.root.findAllByType("Pressable" as never).find(node => node.props.accessibilityLabel === label);
  expect(button("See overview")).toBeUndefined();
  await act(async () => button("Course options")!.props.onPress());
  const dismissMenu = renderer.root.findByType("Modal" as never).props.onDismiss;
  await act(async () => button("View replay")!.props.onPress());
  expect(props.onReplay).not.toHaveBeenCalled();
  await act(async () => dismissMenu());
  expect(props.onReplay).toHaveBeenCalledOnce();
  expect(button("See overview")).toBeUndefined();
  await act(async () => button("Course options")!.props.onPress());
  const toggle = (label: string) => renderer.root.findAllByType("Switch" as never).find(node => node.props.accessibilityLabel === label)!;
  expect(button("View replay")).toBeDefined();
  expect(button("See overview")).toBeDefined();
  expect(["Following", "Recenter", "Zoom in", "Zoom out", "2D map"].every(label => !button(label))).toBe(true);
  expect(toggle("Perspective view").props.value).toBe(true);
  expect(toggle("Space racers").props.value).toBe(true);
  const together = renderer.root.findAllByType("ShapeSource" as never).find(node => node.props.id === "athletes")!.props.shape;
  await act(async () => toggle("Space racers").props.onValueChange(false));
  expect(toggle("Space racers").props.value).toBe(false);
  expect(button("See overview")).toBeDefined();
  expect(renderer.root.findAllByType("ShapeSource" as never).find(node => node.props.id === "athletes")!.props.shape).not.toBe(together);
  await act(async () => toggle("Space racers").props.onValueChange(true));
  await act(async () => toggle("Perspective view").props.onValueChange(false));
  expect(toggle("Perspective view").props.value).toBe(false);
  expect(calls.setCamera.mock.lastCall![0]).toMatchObject({ centerCoordinate: marker.geometry.coordinates, pitch: 0 });
  await act(async () => button("See overview")!.props.onPress());
  expect(button("See overview")).toBeUndefined();
  expect(calls.setCamera.mock.lastCall![0].bounds.ne[0]).toBeLessThan(.02);
  const source = renderer.root.findAllByType("ShapeSource" as never).find(node => node.props.id === "athletes")!;
  await act(async () => source.props.onPress({ features: [{ properties: { id: "you" } }] }));
  expect(props.onSelect).toHaveBeenCalledWith("you");
  const cards = renderer.root.findAllByType("MarkerView" as never);
  expect(cards).toHaveLength(2);
  expect(cards.find(card => card.props.anchor.x === 0)!.props.coordinate).toEqual(marker.geometry.coordinates);
  expect(cards.every(card => card.props.allowOverlap && card.props.allowZElevate === false)).toBe(true);
  const labels = renderer.root.findAllByType("AthletePennant" as never);
  expect(labels.map(label => label.props.detail)).toEqual(["2nd · 0.6 km", "1st · +0.5 km"]);

});

it.each(["km", "mi"])("seeks %s overview targets without changing map pose or athlete selection", async unit => {
  vi.stubGlobal("IS_REACT_ACT_ENVIRONMENT", true);
  const course = createRaceCourse("Corner", [[0, 0], [.01, 0], [.01, .01]]);
  const value = course.length * 1.25 / (unit === "mi" ? 1609.344 : 1000);
  const props = { course, lanes: [{ id: "you", name: "You", initials: "Y", you: true, value: 2 }], unit, selectedId: "you", focusRequest: 0, onSelect: vi.fn(), distanceTarget: { value, request: 1 } };
  await act(async () => { renderer = create(createElement(CourseMap, props), { createNodeMock: element => element.type === "Camera" ? calls : null }); });
  await act(async () => renderer.root.findByType("Observer" as never).props.onCameraChanged({ nativeEvent: { properties: { center: [.005, 0], zoom: 15, pitch: 30, heading: 20, isUserInteraction: true } } }));
  await act(async () => renderer.root.findByType("Map" as never).props.onDidFinishLoadingMap());
  const target = raceCoursePosition(course, raceEffortMetres(value, unit)!).coordinate;
  expect(calls.setCamera.mock.lastCall![0]).toMatchObject({ centerCoordinate: target, zoomLevel: 15, pitch: 30, heading: 20, animationDuration: 0 });
  calls.setCamera.mockClear();
  const repeated = { ...props, distanceTarget: { value, request: 2 } };
  await act(async () => renderer.update(createElement(CourseMap, repeated)));
  expect(calls.setCamera.mock.lastCall![0].centerCoordinate).toEqual(target);
  calls.setCamera.mockClear();
  await act(async () => renderer.update(createElement(CourseMap, { ...repeated, lanes: [{ ...props.lanes[0], value: 3 }] })));
  expect(calls.setCamera).not.toHaveBeenCalled();
  await act(async () => renderer.update(createElement(CourseMap, { ...repeated, lanes: [{ ...props.lanes[0], value: 3 }], distanceTarget: null, focusRequest: 1 })));
  expect(calls.setCamera.mock.lastCall![0].centerCoordinate).toEqual(raceCoursePosition(course, raceEffortMetres(3, unit)!).coordinate);
  expect(props.onSelect).not.toHaveBeenCalled();
  expect(renderer.root.findAllByType("Map" as never)).toHaveLength(1);
});
